"""Best-effort textual blinding; family separation is enforced by the runner.

Normalised matching is shared by import and the independent residual scan.
Original non-identifying prose is retained, including ambiguous common words.
"""
from __future__ import annotations

from functools import lru_cache
from difflib import SequenceMatcher
from pathlib import Path
import re
import unicodedata

import yaml

AMBIGUOUS = frozenset({'opus', 'sonnet', 'haiku', 'gemini', 'codex', 'llama', 'meta', 'claude'})
UNAMBIGUOUS = ('openai', 'anthropic', 'google', 'deepmind', 'microsoft', 'azure',
               'mistral', 'cohere', 'alibaba', 'qwen', 'deepseek', 'xai', 'chatgpt', 'grok')
SELF_REFERENCE = re.compile(
    r"\b(?:i am|i'm|i was built|my (?:model|provider|creator|name)|"
    r'as an? (?:ai|language model)|generated by|powered by|authored by|signed(?: off)? by)\b|'
    r'^\s*(?:signature|signed|author|model(?: credits)?|provider|agent)\s*:', re.MULTILINE)


# Small matching-only skeleton, not a transliteration of surviving prose.
CONFUSABLES = str.maketrans({
    'а': 'a', 'в': 'b', 'с': 'c', 'ԁ': 'd', 'е': 'e', 'һ': 'h',
    'і': 'i', 'ј': 'j', 'к': 'k', 'ӏ': 'l', 'м': 'm', 'о': 'o',
    'р': 'p', 'ѕ': 's', 'т': 't', 'у': 'y', 'х': 'x', 'ѵ': 'v',
    'α': 'a', 'β': 'b', 'ϲ': 'c', 'ε': 'e', 'η': 'n', 'ι': 'i',
    'κ': 'k', 'ν': 'v', 'ο': 'o', 'ρ': 'p', 'τ': 't', 'υ': 'y',
    'χ': 'x', 'ζ': 'z', 'μ': 'm',
})


def normalised_view(content: str) -> tuple[str, list[tuple[int, int]]]:
    """NFKC/case-fold with invisible characters removed, retaining source spans."""
    text, spans = [], []
    # Normalise combining sequences together so compatibility forms and composed
    # characters have the same view. Span mapping keeps benign text byte-for-byte.
    for match in re.finditer(r'[^\r\n][\u0300-\u036f]*|[\r\n]', content):
        for char in unicodedata.normalize('NFKC', match.group()).casefold():
            if unicodedata.category(char) in {'Cf', 'Cc', 'Cs', 'Mn', 'Me'} and char not in '\n\r\t':
                continue
            text.append(char.translate(CONFUSABLES))
            spans.append(match.span())
    return ''.join(text), spans


def fuzzy(identity: str) -> str:
    value, _ = normalised_view(identity)
    value = ''.join(c for c in value if c.isalnum())
    leet = {'a': '[a4@]', 'e': '[e3]', 'i': '[i1!|]', 'o': '[o0]', 's': '[s5$]', 't': '[t7]'}
    # Permit separators between every character; keep alphanumeric boundaries so
    # names embedded in ordinary larger words do not become identity matches.
    return r'(?<![a-z0-9])' + r'[\W_]*'.join(leet.get(c, re.escape(c)) for c in value) + r'(?![a-z0-9])'


def roster_identities(root: Path, tools) -> list[str]:
    identities = set()
    for tool in tools:
        tool_id = tool['id']
        if tool_id.startswith(('agent:', 'agency:', 'skill:3w-')):
            identities.update((tool_id, tool_id.split(':')[-1]))
            identities.update(v for v in (tool.get('name'), tool.get('title')) if isinstance(v, str))
    for path in (root / '.claude/agents').glob('*.md'):
        content = path.read_text(encoding='utf-8')
        if content.startswith('---\n'):
            metadata = yaml.safe_load(content.split('---', 2)[1])
            if isinstance(metadata, dict) and isinstance(metadata.get('name'), str):
                identities.add(metadata['name'])
        identities.add(path.stem)
    return sorted(identities)


def known_identities(run: dict) -> tuple[str, ...]:
    identities = list(run.get('blinding_identities', []))
    for candidate in run['candidates'].values():
        identities += [candidate['tool_id'], candidate.get('maker_model', '')]
        snapshot = candidate.get('registry_snapshot', {})
        identities += [snapshot.get('name', ''), snapshot.get('title', '')]
        identities.append(candidate['tool_id'].split(':')[-1])
    # Registry IDs may be the only names available. Human signatures commonly
    # omit both the namespace and the studio's 3w- prefix.
    identities += [v.split(':')[-1].removeprefix('3w-') for v in identities
                   if isinstance(v, str) and v.split(':')[-1].startswith('3w-')]
    # Bare ambiguous names always need model/attribution context, even when they
    # also appear in the roster. Full model IDs still match unconditionally.
    return tuple(sorted({v for v in identities if isinstance(v, str) and len(v) >= 3
                         and normalised_view(v)[0] not in AMBIGUOUS}, key=len, reverse=True))


@lru_cache(maxsize=32)
def identity_patterns(known: tuple[str, ...]) -> tuple[re.Pattern, ...]:
    names = '|'.join(fuzzy(v) for v in sorted(set(UNAMBIGUOUS) | set(known), key=len, reverse=True))
    ambiguous = '(?:' + '|'.join(fuzzy(v) for v in sorted(AMBIGUOUS)) + ')'
    model_context = r'(?:model|agent|assistant|llm|ai|credits?|provider)'
    separator = r'[\s_/-]*'
    version = r'\d+(?:[.-]\d+)*(?:-\d{4}-\d{2}-\d{2})?'
    tier = r'(?:opus|sonnet|haiku|pro|flash|lite|sol|astra|luna|mini|nano|codex|latest)'
    suffix = r'(?:' + separator + tier + r')*'
    provider = r'(?:(?:openai|anthropic|google|azure|deepmind)' + separator + r')?'
    complete_model = provider + r'(?:' + (
        r'(?:gpt|codex|gemini)' + separator + version + suffix + r'|'
        r'(?:claude' + separator + r')?(?:opus|sonnet|haiku)' + separator + version + suffix + r'|'
        r'claude' + separator + version + separator + r'(?:opus|sonnet|haiku)'
    ) + r')(?![a-z0-9])'
    return (
        re.compile(r'(?<![a-z0-9])' + complete_model),
        re.compile(names),
        re.compile(r'\b(?:skill|agent|agency|tool)\s*:\s*[\w:./-]+'),
        re.compile(fuzzy('gpt') + r'[\W_]*\d[\w.-]*|\bo[134](?:-[\w.-]+)?\b'),
        # Version suffixes, provider adjacency and explicit model-attribution
        # context disambiguate poetry, astronomical names and manuscript terms.
        re.compile(ambiguous + r'(?:[\W_]*\d[\w.-]*|[\W_]+' + model_context + r'\b)'),
        re.compile(r'\b' + model_context + r'[\W_]+' + ambiguous),
        re.compile(r'(?:' + '|'.join(fuzzy(v) for v in UNAMBIGUOUS) + r')[\W_]+' + ambiguous),
        re.compile(ambiguous + r'[\W_]+(?:(?:by|from)[\W_]+)?(?:' + '|'.join(fuzzy(v) for v in UNAMBIGUOUS) + ')'),
        re.compile(r'\b(?:made|written|generated|authored|powered)\s+(?:by|with|using)\s+' + ambiguous),
    )


def identity_spans(content: str, run: dict) -> list[tuple[int, int]]:
    view, source = normalised_view(content)
    matches = []
    for pattern in identity_patterns(known_identities(run)):
        matches.extend(m.span() for m in pattern.finditer(view))
    for match in re.finditer(r'^.*$', view, re.MULTILINE):
        if SELF_REFERENCE.search(match.group()):
            matches.append(match.span())
    identity_tokens = set()
    for identity in known_identities(run):
        identity_tokens.update(re.findall(r'[a-z]{4,}', normalised_view(identity)[0]))
    source_matches = [(source[start][0], source[end - 1][1])
                      for start, end in matches if end > start]
    for token in re.finditer(r'[^\W\d_]+', content):
        scripts = {unicodedata.name(c, '').split(' ')[0] for c in token.group() if c.isalpha()}
        if 'LATIN' in scripts and scripts.intersection({'CYRILLIC', 'GREEK'}):
            skeleton, _ = normalised_view(token.group())
            if any(SequenceMatcher(None, skeleton, name).ratio() >= 0.8 for name in identity_tokens):
                source_matches.append(token.span())
    return sorted(source_matches)


def sanitise(content: str, run: dict) -> str:
    merged = []
    for start, end in identity_spans(content, run):
        if merged and start <= merged[-1][1]:
            merged[-1] = (merged[-1][0], max(end, merged[-1][1]))
        else:
            merged.append((start, end))
    for start, end in reversed(merged):
        content = content[:start] + '[identity redacted]' + content[end:]
    return content.rstrip('\n') + '\n'


def check_blind(content: str, run: dict) -> None:
    """Never silently repair a packet; independent checker review is also required."""
    if identity_spans(content, run):
        raise ValueError('residual maker identity/signature in packet; sanitise inputs and prepare a new run')
