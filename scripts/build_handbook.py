from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

try:
    from .oscheck.cards import ACTIVE_ROLES, check_cards, load_registry, read_cards
    from .oscheck.common import relative_path
except ImportError:
    from oscheck.cards import ACTIVE_ROLES, check_cards, load_registry, read_cards
    from oscheck.common import relative_path

ROOT = Path(__file__).resolve().parents[1]


def label(value: str) -> str:
    return value.replace('-', ' ').capitalize()


def table_text(value: object) -> str:
    return ' '.join(str(value).split()).replace('|', r'\|')


def first_sentence(body: str) -> str:
    """Read the introductory paragraph after the H1, never a fenced prompt."""
    lines = body.splitlines()
    title = next((i for i, line in enumerate(lines) if re.match(r'^ {0,3}#\s', line)), -1)
    paragraph = []
    for line in lines[title + 1:]:
        stripped = line.strip()
        if not stripped:
            if paragraph:
                break
            continue
        if stripped.startswith(('#', '```', '~~~', '- ', '* ', '+ ', '>', '|')):
            break
        paragraph.append(stripped)
    prose = ' '.join(paragraph)
    prose = re.sub(r'!?\[([^\]]+)\]\([^)]*\)', r'\1', prose)
    prose = re.sub(r'[`*_~]', '', prose)
    return re.split(r'(?<=[.!?])\s+', prose, maxsplit=1)[0] or 'Not documented.'


def markdown_page(title: str, lines: list[str]) -> str:
    # A stable generation date, not a claim of a fresh human review on every run.
    metadata = [
        '---', f'title: {title}', 'type: guide', 'status: proposed',
        'owner: founder', 'last_reviewed: 2026-10-23', '---', '',
        f'# {title}', '',
        '<!-- Generated by scripts/build_handbook.py; do not edit. -->', '',
    ]
    return '\n'.join(metadata + lines).rstrip() + '\n'


def build_handbook(root: Path = ROOT) -> dict[str, str]:
    schema = root / 'schemas/metadata.json'
    config = json.loads(schema.read_text(encoding='utf-8')) if schema.exists() else {}
    errors = [i for i in check_cards(root, config) if i.severity == 'error']
    if errors:
        raise ValueError('\n'.join(i.render() for i in errors))
    tools, by_id = load_registry(root)
    cards = read_cards(root, by_id)
    materials = json.loads((root / 'toolkit/sources/materials.json').read_text(encoding='utf-8'))
    if not isinstance(materials, dict):
        raise ValueError('materials must be an id-to-material mapping')
    rows = []
    for tool in sorted(tools, key=lambda t: (t['department'], t['sub_department'], t['job'], t['role'] != 'lead', t['id'])):
        if tool['role'] not in ACTIVE_ROLES:
            continue
        card = cards.get(tool['id'])
        data = card[1] if card else {}
        material = materials.get(tool['id'], {})
        rows.append({
            'id': tool['id'], 'department': tool['department'],
            'sub_department': tool['sub_department'], 'job': tool['job'],
            'role': tool['role'], 'trigger': tool.get('trigger', ''),
            'invoke': data.get('invoke'), 'availability': data.get('availability'),
            'distribution': data.get('distribution', material.get('distribution')),
            'card': relative_path(root, card[0]) if card else None,
            'summary': first_sentence(card[2]) if card else 'Card pending.',
        })
    outputs = {'toolkit/cards/index.json': json.dumps({'schema_version': 1, 'tools': rows}, indent=2, ensure_ascii=False) + '\n'}
    departments = sorted({t['department'] for t in tools})
    overview = [
        'Find the job you need, then read its lead card. A card explains the inputs, invocation, passing output and limits of one tool.', '',
        '## For humans', '',
        'Choose a department below, then a sub-department and job. Start with its lead. Call a specialist only when its recorded trigger applies. “Card pending” means the instructions have not yet been written; it does not establish readiness.', '',
        'Bench and parked tools appear as a compact library at the end of each department. Use them only by explicit request after reviewing their reason and prerequisites. Maker ≠ checker: a separate reviewer checks the result; the founder makes approvals.', '',
        '## For agents', '',
        'Read [toolkit/cards/index.json](../toolkit/cards/index.json), filter by department and job, choose the lead first, then read only the chosen card and follow its “How to run it” section. Load a specialist only on its trigger. Do not load every card or the whole handbook into context.', '',
        'The index includes every lead and specialist, even during rollout. Paths are relative to the repository root. A null card, invocation or availability means it is not documented by a card yet. Distribution falls back to materials.json when a card is pending. Availability never proves authentication or connectivity.', '',
        '## Departments and card coverage', '',
        'Coverage counts cards against registry leads and specialists, including aliases resolved to canonical IDs. It measures documentation presence, not approval or tool quality.', '',
        '| Department | Cards | Lead/specialist tools | Coverage |',
        '| --- | ---: | ---: | ---: |',
    ]
    for department in departments:
        active = [r for r in rows if r['department'] == department]
        count = sum(r['card'] is not None for r in active)
        percent = 100 * count / len(active) if active else 100
        overview.append(f'| [{label(department)}]({department}.md) | {count} | {len(active)} | {percent:.1f}% |')
        lines = [
            f'Use this guide alongside the [department charter](../studio/departments/{department}.md). The [registry](../toolkit/sources/registry.json) owns routing; cards document use. All generated guidance retains its source review state.', '',
            f'Card coverage: **{count}/{len(active)} ({percent:.1f}%)** lead/specialist tools. Start with the lead; maker ≠ checker.', '',
        ]
        groups: dict[str, dict[str, list[dict]]] = defaultdict(lambda: defaultdict(list))
        for row in active:
            groups[row['sub_department']][row['job']].append(row)
        for sub_department, jobs in sorted(groups.items()):
            lines.extend([f'## {label(sub_department)}', ''])
            for job, entries in sorted(jobs.items()):
                lines.extend([f'### {label(job)}', ''])
                leads = [r for r in entries if r['role'] == 'lead']
                if not leads:
                    lines.extend(['No lead is assigned in the registry; agree a human owner before starting.', ''])
                for row in entries:
                    identity = f"`{row['id']}`"
                    if row['card']:
                        identity = f"[{identity}](../{row['card']})"
                        detail = table_text(row['summary'])
                    else:
                        detail = 'card pending'
                    prefix = 'Lead' if row['role'] == 'lead' else 'Specialist'
                    lines.append(f'- **{prefix}:** {identity} — {detail}')
                    if row['role'] == 'specialist':
                        lines.append(f"  Trigger: {table_text(row['trigger'])}")
                lines.append('')
        lines.extend(['## Bench and parked', '', 'Library tools are available only by explicit request after source and prerequisite review.', ''])
        library = sorted((t for t in tools if t['department'] == department and t['role'] in {'bench', 'parked'}), key=lambda t: t['id'])
        if library:
            lines.extend(['| ID | Role | Reason |', '| --- | --- | --- |'])
            for tool in library:
                lines.append(f"| `{table_text(tool['id'])}` | {tool['role']} | {table_text(tool.get('reason', 'Not documented.'))} |")
        else:
            lines.append('No bench or parked tools in the registry.')
        outputs[f'handbook/{department}.md'] = markdown_page(f'{label(department)} tool handbook', lines)
    overview.extend(['', '## Updating the handbook', '',
        'Edit source cards using the [card standard](../docs/tool-cards.md), then run `uv run python scripts/build_handbook.py` and `uv run python scripts/build_index.py`. Never edit these generated pages or the routing index by hand. Run `uv run python scripts/validate.py` before review.', ''])
    outputs['handbook/README.md'] = markdown_page('Tool handbook', overview)
    outputs['toolkit/cards/README.md'] = markdown_page('Tool cards', [
        'One source card per registry lead or specialist, organised as `<department>/<sub_department>/<slug>.md`. Bench and parked tools have no cards.', '',
        'Read the [card standard](../../docs/tool-cards.md) before adding or updating a card. Read the tool’s own source; document only what it supports. Maker ≠ checker: another person or agent instance reviews the card and its output.', '',
        'For a human overview, use the [handbook](../../handbook/README.md). Agents read [index.json](index.json), filter by department and job, then open only the chosen card and follow “How to run it”. Leads come first; specialists need a matching trigger.', '',
        '`index.json` and this README are generated by `uv run python scripts/build_handbook.py`. Card paths in the index are relative to the repository root. Pending cards and undocumented invocation/availability values are null; source cards remain the editable records.', '',
        'Validate with `uv run python scripts/validate.py`. Missing lead/specialist cards warn by department during rollout; `--strict-cards` or `cards.strict_departments` in the metadata schema makes coverage mandatory. Generated files must always be current.',
    ])
    return outputs


def stale_outputs(root: Path, expected: dict[str, str]) -> list[str]:
    stale = []
    for name, text in expected.items():
        try:
            if (root / name).read_text(encoding='utf-8') == text:
                continue
        except FileNotFoundError:
            pass
        stale.append(name)
    stale.extend(relative_path(root, p) for p in (root / 'handbook').glob('*.md') if relative_path(root, p) not in expected)
    return sorted(stale)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description='Generate the human tool handbook and agent routing index.')
    parser.add_argument('--check', action='store_true', help='fail if generated files are missing, stale or obsolete')
    args = parser.parse_args(argv)
    try:
        expected = build_handbook(ROOT)
        stale = stale_outputs(ROOT, expected)
        if args.check:
            if stale:
                print('Handbook is stale; run `uv run python scripts/build_handbook.py`: ' + ', '.join(stale))
                return 1
            print('Handbook and card index are current.')
            return 0
        for name, text in expected.items():
            path = ROOT / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8')
        for name in stale:
            if name not in expected:
                (ROOT / name).unlink()
        print(f'Wrote {len(expected)} handbook and routing files.')
        return 0
    except (OSError, ValueError, TypeError, KeyError) as exc:
        print(f'Cannot build handbook: {exc}')
        return 1


if __name__ == '__main__':
    sys.exit(main())
